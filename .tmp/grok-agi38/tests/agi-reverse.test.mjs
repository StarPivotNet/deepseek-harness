import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const PRESET_ROOT = fileURLToPath(new URL('..', import.meta.url))
const SKILL_DIR = join(PRESET_ROOT, 'skills', 'agi-reverse')
const SKILL = join(SKILL_DIR, 'SKILL.md')
const LIBRARY = join(SKILL_DIR, 'library')
const VMP = join(LIBRARY, 're-vmp', 'SKILL.md')
const SUPERPOWERS = join(PRESET_ROOT, 'skills', 'using-superpowers', 'SKILL.md')
const PERSONA = join(PRESET_ROOT, 'agent.cordis.yml')

describe('agi-reverse keeps the rev-skills library inside the preset', () => {
  it('names the skill and stops on a VMProtect PE', () => {
    const text = readFileSync(SKILL, 'utf8')
    assert.match(text, /^---\r?\nname: agi-reverse\r?\n/)
    assert.match(text, /VMProtect PE/)
    assert.match(text, /<skill_base>\\library\\re-vmp\\SKILL\.md/)
    assert.match(text, /Stop this list/)
    assert.equal(text.includes('de-vmprotect'), false)
    assert.match(text, /<skill_base>\\library/)
    assert.match(text, /probe\.ps1/)
    assert.equal(text.includes('rev-skills-main'), false)
    assert.equal(text.includes('rea_inspect'), false)
    assert.equal(existsSync(join(PRESET_ROOT, 'skills', 'de-vmprotect')), false)
    assert.equal(existsSync(join(SKILL_DIR, 'vmp')), false)
  })

  it('stores re-vmp in the library with English sections', () => {
    const text = readFileSync(VMP, 'utf8')
    assert.match(text, /^---\r?\nname: re-vmp\r?\n/)
    assert.match(text, /capabilities: \[unpack, emulation, pe-parser, key-extraction\]/)
    assert.match(text, /## When to use \/ when not to use/)
    assert.match(text, /## Tools/)
    assert.match(text, /## Steps/)
    assert.match(text, /## Related files/)
    assert.match(text, /## Pitfalls/)
    assert.match(text, /<skill_base>\\library\\re-vmp\\vmp3104\.py/)
    assert.equal(existsSync(join(LIBRARY, 're-vmp', 'vmp3104.py')), true)
    assert.equal(existsSync(join(LIBRARY, 're-vmp', 'catalog', 'ntdll.dll')), true)
  })

  it('stores the gateway files and the license next to the skill', () => {
    const skill = readFileSync(SKILL, 'utf8')
    assert.match(skill, /re-binary-core\\SKILL\.md/)
    assert.match(skill, /re-vmp\\SKILL\.md/)
    assert.match(skill, /re-rpk\\SKILL\.md/)
    assert.match(skill, /Stop this list/)
    assert.equal(skill.includes('rpk-analysis-and-crack'), false)
    assert.equal(existsSync(join(LIBRARY, 're-rpk', 'cli.js')), true)
    assert.equal(existsSync(join(LIBRARY, 're-rpk', 'vendor', 'sign', 'SignUtil.js')), true)
    assert.equal(existsSync(join(PRESET_ROOT, 'skills', 'rpk-analysis-and-crack')), false)
    assert.match(skill, /re-format-pe/)
    assert.equal(skill.includes('references/routes.md'), false)
    assert.equal(existsSync(join(SKILL_DIR, 'references', 'routes.md')), false)
    assert.equal(skill.includes('de-vmprotect'), false)
    assert.equal(skill.includes('rev-skills-main'), false)
    assert.equal(existsSync(join(LIBRARY, 're-binary-core', 'SKILL.md')), true)
    assert.equal(existsSync(join(LIBRARY, 're-analyze', 'references', 'triage.md')), true)
    assert.equal(existsSync(join(LIBRARY, 'LICENSE-docs.md')), true)
    const probe = readFileSync(join(SKILL_DIR, 'probe.ps1'), 'utf8')
    assert.match(probe, /HAVE:/)
    assert.equal(probe.includes('Invoke-WebRequest'), false)
    assert.equal(probe.includes('choco install'), false)
    const bundled = readdirSync(LIBRARY, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && existsSync(join(LIBRARY, entry.name, 'SKILL.md')))
    assert.equal(bundled.length, 124)
  })

  it('is reached from using-superpowers as one skill', () => {
    const text = readFileSync(SUPERPOWERS, 'utf8')
    const persona = readFileSync(PERSONA, 'utf8')
    assert.match(text, /`agi-reverse`/)
    assert.match(text, /including a VMProtect PE/)
    assert.equal(text.includes('de-vmprotect'), false)
    assert.match(text, /re-rpk/)
    assert.equal(text.includes('rpk-analysis-and-crack'), false)
    assert.match(persona, /library\\re-vmp\\SKILL\.md/)
    assert.match(persona, /do not call `skill` for `re-vmp`/)
    assert.match(persona, /library\\re-rpk\\SKILL\.md/)
    assert.match(persona, /do not call `skill` for `re-rpk`/)
  })
})
